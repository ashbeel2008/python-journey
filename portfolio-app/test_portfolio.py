"""Tests for the portfolio app.

Run from the portfolio-app folder:

    python test_portfolio.py

Do not edit this file to make tests pass. Edit the code until it is correct.
"""

import json
import os
import tempfile

from portfolio_core import display, loader

SAMPLE = {
    "name": "Miraal Fatima",
    "headline": "Python developer in training",
    "about": "One hour a day.",
    "location": "",
    "email": "",
    "links": [
        {"label": "GitHub", "url": "https://github.com/ashbeel2008"},
        {"label": "YouTube", "url": ""},
    ],
    "skills": [{"name": "Python", "level": "learning"}],
    "projects": [
        {
            "title": "python-journey",
            "description": "Daily practice.",
            "url": "https://github.com/ashbeel2008/python-journey",
            "status": "in progress",
            "tags": ["python"],
        }
    ],
    "achievements": [
        {"title": "First commit", "date": "2026-11", "note": "Pushed to GitHub."}
    ],
}

results = []


def check(label, fn):
    try:
        fn()
        results.append((label, True, ""))
    except AssertionError as error:
        results.append((label, False, str(error) or "assertion failed"))
    except Exception as error:
        results.append((label, False, type(error).__name__ + ": " + str(error)))


def write_json(path, data):
    with open(path, "w", encoding="utf-8") as f:
        json.dump(data, f)


def temp_path(name):
    folder = tempfile.mkdtemp()
    return os.path.join(folder, name)


# ----------------------------------------------------------------- tests


def t01_load_valid():
    path = temp_path("good.json")
    write_json(path, SAMPLE)
    data = loader.load_portfolio(path)
    assert data["name"] == "Miraal Fatima"


def t02_roundtrip():
    path = temp_path("roundtrip.json")
    loader.save_portfolio(SAMPLE, path)
    data = loader.load_portfolio(path)
    assert data == SAMPLE


def t03_missing_file():
    path = temp_path("does-not-exist.json")
    try:
        loader.load_portfolio(path)
    except loader.PortfolioError:
        return
    raise AssertionError("expected PortfolioError for a missing file")


def t04_bad_json():
    path = temp_path("broken.json")
    with open(path, "w", encoding="utf-8") as f:
        f.write("{ this is not json")
    try:
        loader.load_portfolio(path)
    except loader.PortfolioError:
        return
    raise AssertionError("expected PortfolioError for broken JSON")


def t05_missing_key():
    path = temp_path("incomplete.json")
    broken = dict(SAMPLE)
    del broken["projects"]
    write_json(path, broken)
    try:
        loader.load_portfolio(path)
    except loader.PortfolioError:
        return
    raise AssertionError("expected PortfolioError for a missing key")


def t06_render_all():
    text = display.render_all(SAMPLE)
    assert "MIRAAL FATIMA" in text
    assert "python-journey" in text
    assert "First commit" in text


def t07_render_one_section():
    text = display.render_section(SAMPLE, "projects")
    assert "python-journey" in text
    assert "SKILLS" not in text


def t08_skip_empty_link():
    text = display.render_links(SAMPLE)
    assert "GitHub" in text
    assert "YouTube" not in text


def t09_unknown_section():
    try:
        display.render_section(SAMPLE, "nonsense")
    except KeyError:
        return
    raise AssertionError("expected KeyError for an unknown section")


def t10_empty_projects():
    data = dict(SAMPLE)
    data["projects"] = []
    text = display.render_projects(data)
    assert "(no projects yet)" in text


TESTS = [
    ("01 load valid file", t01_load_valid),
    ("02 save then load", t02_roundtrip),
    ("03 missing file", t03_missing_file),
    ("04 broken JSON", t04_bad_json),
    ("05 missing key", t05_missing_key),
    ("06 render everything", t06_render_all),
    ("07 render one section", t07_render_one_section),
    ("08 skip empty link", t08_skip_empty_link),
    ("09 unknown section", t09_unknown_section),
    ("10 empty project list", t10_empty_projects),
]

for label, fn in TESTS:
    check(label, fn)

passed = sum(1 for _, ok, _ in results if ok)

print()
for label, ok, error in results:
    mark = "PASS" if ok else "FAIL"
    line = "[" + mark + "] " + label
    if error:
        line += "  ->  " + error
    print(line)

print()
print(str(passed) + "/" + str(len(results)) + " passing")

if passed == len(results):
    print("Portfolio core works. Now run: python main.py")
else:
    print("Fix the FAILs above before building the GUI.")

import os
import tempfile

import exercises as ex

results = []


def check(label, fn):
    try:
        fn()
        results.append((label, True, ""))
    except AssertionError as e:
        results.append((label, False, str(e) or "assertion failed"))
    except Exception as e:
        results.append((label, False, f"{type(e).__name__}: {e}"))


def t01():
    assert ex.welcome("Steve") == "Welcome, Steve!"


def t02():
    assert ex.player_status("Alex", 20) == "Alex: 20 HP"


def t03():
    assert ex.format_time(125) == "02:05"
    assert ex.format_time(59) == "00:59"
    assert ex.format_time(3600) == "60:00"


def t04():
    assert ex.check_health(10) == "Alive"
    assert ex.check_health(1) == "Alive"
    assert ex.check_health(0) == "You died"
    assert ex.check_health(-5) == "You died"


def t05():
    assert ex.count_items(["sword", "pickaxe", "torch"]) == 3
    assert ex.count_items([]) == 0


def t06():
    assert ex.apply_damage(20, 7) == 13
    assert ex.apply_damage(5, 10) == 0
    assert ex.apply_damage(0, 3) == 0


def t07():
    assert ex.best_score([3, 9, 4]) == 9
    assert ex.best_score([-1, -5]) == -1
    assert ex.best_score([]) is None


def t08():
    assert ex.count_blocks(["dirt", "stone", "dirt"]) == {"dirt": 2, "stone": 1}
    assert ex.count_blocks([]) == {}


def t09():
    profile = {"name": "Alex", "level": 12}
    path = os.path.join(tempfile.gettempdir(), "mc_profile_test.json")
    ex.save_profile(path, profile)
    loaded = ex.load_profile(path)
    assert loaded == profile, f"expected {profile}, got {loaded}"
    if os.path.exists(path):
        os.remove(path)


def t10():
    assert ex.safe_int("42") == 42
    assert ex.safe_int("-7") == -7
    assert ex.safe_int("abc") is None


tests = [
    ("01 welcome", t01),
    ("02 player_status", t02),
    ("03 format_time", t03),
    ("04 check_health", t04),
    ("05 count_items", t05),
    ("06 apply_damage", t06),
    ("07 best_score", t07),
    ("08 count_blocks", t08),
    ("09 save/load profile", t09),
    ("10 safe_int", t10),
]

for label, fn in tests:
    check(label, fn)

passed = sum(1 for _, ok, _ in results if ok)

print()
for label, ok, err in results:
    mark = "PASS" if ok else "FAIL"
    line = f"[{mark}] {label}"
    if err:
        line += f"  ->  {err}"
    print(line)

print()
print(f"{passed}/{len(results)} passing")

if passed == len(results):
    print("Week 1 complete. Commit this and start the Clip Idea Tracker.")
else:
    print("Fix the FAILs above. Read the error, then the hint in exercises.py.")
